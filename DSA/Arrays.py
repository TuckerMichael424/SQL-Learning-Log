# ARRAYS - A linear data structure that stores a collection of elements of the same data type congtigously (one after the other) in memory,
 
    # with each element assigned an "index" (i.e. a number that represents its position in the array). 

        # It helps to think of an array as a flight of stairs, with each element being a step.

    # OPERATIONS ON ARRAYS:
        # Arrays can be traversed (iterated through each element), and can have elements inserted, deleted, and updated. The last three operations require
        # an index to be specified. 

    # TYPES OF ARRAYS: 
        # There are two types of arrays: 
            # One Dimensional Array - A simple linear array (like the stair concept)

            # Multidimensional Array - An array of arrays (like a 2D array)